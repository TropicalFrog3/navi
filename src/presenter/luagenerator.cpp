bool LuaGenerator::generateForApp(uint32_t appId)
{
    if (appId == 0) return false;

    // Check if we have keys configured for this app in depot_keys.yaml
    if (!DepotKeys::hasKeysForApp(appId))
    {
        return false;
    }

    std::unordered_set<uint32_t> configuredDepots = DepotKeys::getDepotsForApp(appId);

    // Resolve destination directory
    std::string pluginDir = g_config.getPluginDir();
    if (pluginDir.empty())
    {
        pluginDir = Paths::stplugDir();
    }
    if (pluginDir.empty())
    {
        LOG_WARN("LuaGenerator: Unable to determine stplug-in directory for app %u\n", appId);
        return false;
    }

    std::error_code ec;
    std::filesystem::create_directories(pluginDir, ec);

    // Query Steam's appinfo for the depots section
    std::vector<AppInfoHelper::DepotInfo> appinfoDepots;
    bool hasAppInfo = false;

    if (g_pClientApps)
    {
        std::vector<char> buf(512 * 1024); // 512KB buffer
        uint32_t bytesRead = g_pClientApps->getAppDataSection(appId, k_EAppInfoSectionDepots, buf.data(), buf.size());
        if (bytesRead > 0)
        {
            appinfoDepots = AppInfoHelper::parseDepotsSection(buf.data(), bytesRead);
            hasAppInfo = !appinfoDepots.empty();
        }
        else
        {
            LOG_INFO("LuaGenerator: Appinfo depots section empty for app %u, requesting update...\n", appId);
            const AppId_t appList[1] = { appId };
            g_pClientApps->requestAppInfoUpdate(appList, 1);
        }
    }
    else
    {
        LOG_INFO("LuaGenerator: g_pClientApps not initialized yet for app %u, generating fallback key lua\n", appId);
    }

    // Map depotId -> DepotInfo for fast lookup
    std::unordered_map<uint32_t, AppInfoHelper::DepotInfo> infoMap;
    for (const auto& d : appinfoDepots)
    {
        infoMap[d.depotId] = d;
    }

    std::ostringstream lua;
    lua << "-- Auto-generated by SLSsteam from depot_keys.yaml\n";
    lua << "addappid(" << appId << ", 1, \"0\")\n";

    size_t keysEmitted = 0;
    size_t manifestsEmitted = 0;

    // 1. Emit depots configured in depot_keys.yaml
    for (uint32_t depotId : configuredDepots)
    {
        std::string hexKey = DepotKeys::getDepotKey(depotId);
        if (!hexKey.empty())
        {
            lua << "addappid(" << depotId << ", 0, \"" << hexKey << "\")\n";
            keysEmitted++;
        }

        auto it = infoMap.find(depotId);
        if (it != infoMap.end() && it->second.manifestGid != 0)
        {
            if (it->second.maxsize > 0)
            {
                lua << "setManifestid(" << depotId << ", \"" << it->second.manifestGid << "\", " << it->second.maxsize << ")\n";
            }
            else
            {
                lua << "setManifestid(" << depotId << ", \"" << it->second.manifestGid << "\")\n";
            }
            manifestsEmitted++;
        }
    }

    // 2. Also emit any additional depots found in appinfo that belong to this app (e.g. unencrypted content)
    for (const auto& d : appinfoDepots)
    {
        if (configuredDepots.count(d.depotId) == 0 && d.manifestGid != 0)
        {
            if (d.maxsize > 0)
            {
                lua << "setManifestid(" << d.depotId << ", \"" << d.manifestGid << "\", " << d.maxsize << ")\n";
            }
            else
            {
                lua << "setManifestid(" << d.depotId << ", \"" << d.manifestGid << "\")\n";
            }
            manifestsEmitted++;
        }
    }

    std::string luaPath = pluginDir + "/" + std::to_string(appId) + ".lua";
    if (!AtomicFile::write(luaPath, lua.str(), false))
    {
        LOG_ERROR("LuaGenerator: Failed to write %s\n", luaPath.c_str());
        return false;
    }

    LOG_INFO("LuaGenerator: Generated %s (%zu key(s), %zu manifest(s), hasAppInfo=%d)\n",
             luaPath.c_str(), keysEmitted, manifestsEmitted, hasAppInfo ? 1 : 0);

    return true;
}

size_t LuaGenerator::syncAllAppsWithKeys()
{
    auto apps = DepotKeys::getAllAppIdsWithKeys();
    size_t count = 0;
    for (uint32_t appId : apps)
    {
        if (generateForApp(appId))
        {
            count++;
        }
    }
    LOG_INFO("LuaGenerator: Synced %zu/%zu app plugin(s) from depot_keys.yaml\n",
             count, apps.size());
    return count;
}
